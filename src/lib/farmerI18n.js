const isLang = (code) => FARMER_LANGUAGES.some((l) => l.code === code);

function readSavedLang() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return isLang(v) ? v : 'en';
  } catch {
    return 'en';
  }
}

/** Plain translate function for a language (also usable outside React). */
export function translate(lang, key, vars) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

/** Every key must exist in every language (used by tests). */
export function missingTranslations() {
  const keys = Object.keys(STRINGS.en);
  return Object.fromEntries(
    Object.keys(STRINGS)
      .filter((lang) => lang !== 'en')
      .map((lang) => [lang, keys.filter((k) => !(k in STRINGS[lang]))]),
  );
}

const FarmerI18nContext = createContext(null);

/** State for the provider: the chosen language, saved on this device. */
export function useFarmerLanguageState() {
  const [lang, setLangState] = useState(readSavedLang);
  const setLang = useCallback((code) => {
    if (!isLang(code)) return;
    setLangState(code);
    try { localStorage.setItem(STORAGE_KEY, code); } catch { /* not saved; still applies now */ }
  }, []);
  useEffect(() => {
    // Screen readers pronounce the page in the right language.
    document.documentElement.lang = lang === 'en' ? 'en' : lang;
    return () => { document.documentElement.lang = 'en'; };
  }, [lang]);
  const t = useCallback((key, vars) => translate(lang, key, vars), [lang]);
  return useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
}

export function FarmerI18nProvider({ value, children }) {
  return createElement(FarmerI18nContext.Provider, { value }, children);
}

/** { t, lang, setLang } — English if used outside the farmer portal. */
export function useFarmerT() {
  return useContext(FarmerI18nContext) || { lang: 'en', setLang: () => {}, t: (key, vars) => translate('en', key, vars) };
}
